def our_price(competitor: int) -> int:
    """На 300 ₽ дешевле; там, где это больше трети цены, — на 10% дешевле с «девяткой» на конце."""
    if competitor >= 600:
        return competitor - 300
    p = int(competitor * 0.9)
    return max(29, p - (p % 10) - 1 if p % 10 != 9 else p)


